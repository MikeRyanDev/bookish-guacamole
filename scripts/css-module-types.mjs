import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { preprocessCSS, resolveConfig } from "vite";

// Generate from Vite's actual exports, including cross-feature @value imports.
// Checked-in declarations make misspelled/removed class names TypeScript errors.
const directory = resolve("src/client/styles");
const config = await resolveConfig({}, "build");
let stale = false;
for (const name of (await readdir(directory)).filter((name) => name.endsWith(".module.css"))) {
  const file = resolve(directory, name);
  const result = await preprocessCSS(await readFile(file, "utf8"), file, config);
  const declaration = `// Generated by pnpm styles:types. Do not edit.\ndeclare const styles: {\n${Object.keys(
    result.modules ?? {},
  )
    .sort()
    .map((key) => `  readonly ${key}: string;`)
    .join("\n")}\n};\nexport default styles;\n`;
  if (process.argv.includes("--check")) {
    const current = await readFile(`${file}.d.ts`, "utf8").catch(() => "");
    if (current !== declaration) {
      console.error(`Stale CSS types: ${name}. Run pnpm styles:types.`);
      stale = true;
    }
  } else await writeFile(`${file}.d.ts`, declaration);
}
if (stale) process.exitCode = 1;
